/** A figure without its currency (the header names it once): cents only for small euro and dollar amounts. */
export const plainAmount = (value: number, currency: string, locale: string): string => {
  const digits = Math.abs(value) < 100 && currency !== 'RSD' ? 2 : 0;
  return new Intl.NumberFormat(locale, { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(value);
};
