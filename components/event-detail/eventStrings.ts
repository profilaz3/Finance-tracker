/** "{count} expenses" and the like in the app language's plural form. */
export const countText = (count: number, language: AppLanguage, one: string, few: string, other: string): string =>
  pluralText(count, language, { one, few, other });

/** Whole dinars; euros and dollars with cents only when there are any (€420, €207.80). */
export const eventAmount = (value: number, currency: Currency, language: AppLanguage): string => {
  const cents = currency !== 'RSD' && Math.round(Math.abs(value) * 100) % 100 !== 0;
  const digits = cents ? 2 : 0;
  return formatMoney(value, currency, language, { minimumFractionDigits: digits, maximumFractionDigits: digits });
};
