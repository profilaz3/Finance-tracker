import type { Currency, RecurrenceFrequency, RecurringTransaction, Transaction } from '../types';
import { merchantTokens, normalizeMerchant } from './merchantMemory';

/**
 * Finds subscriptions hiding in transaction history: the same shop charging a similar amount on a
 * regular cadence, that the user has not set up as a recurring transaction yet. Pure and
 * deterministic so it can run on every render (memoized by the caller) and in tests.
 */

const DAY_MS = 86_400_000;
const AVG_MONTH_DAYS = 30.4375;

export type SubscriptionCadence = 'weekly' | 'biweekly' | 'monthly' | 'quarterly' | 'yearly';

interface CadenceRule {
  cadence: SubscriptionCadence;
  days: number;
  min: number;
  max: number;
  /** Charges needed before the pattern counts. */
  minCount: number;
}

const CADENCES: readonly CadenceRule[] = [
  { cadence: 'weekly', days: 7, min: 5, max: 9, minCount: 4 },
  { cadence: 'biweekly', days: 14, min: 11, max: 17, minCount: 3 },
  { cadence: 'monthly', days: AVG_MONTH_DAYS, min: 26, max: 35, minCount: 3 },
  { cadence: 'quarterly', days: 91.3, min: 80, max: 100, minCount: 3 },
  { cadence: 'yearly', days: 365.25, min: 350, max: 380, minCount: 2 },
];

/** Cadences that map onto a RecurringTransaction frequency ("Track as recurring"). */
export const CADENCE_FREQUENCY: Partial<Record<SubscriptionCadence, RecurrenceFrequency>> = {
  weekly: 'weekly',
  biweekly: 'biweekly',
  monthly: 'monthly',
  yearly: 'yearly',
};

export interface PriceIncrease {
  from: number;
  to: number;
  /** Fractional rise, e.g. 0.12 for 12 %. */
  pct: number;
  /** ISO date of the first charge at the new price. */
  date: string;
}

export interface DetectedSubscription {
  /** Stable id: merchant key plus currency. */
  id: string;
  key: string;
  /** Most recent original spelling of the merchant. */
  label: string;
  currency: Currency;
  cadence: SubscriptionCadence;
  periodDays: number;
  /** Latest charge amount. */
  amount: number;
  count: number;
  firstDate: string;
  lastDate: string;
  /** Next expected charge (ISO date, yyyy-mm-dd). */
  nextDate: string;
  monthlyCost: number;
  yearlyCost: number;
  confidence: number;
  status: 'active' | 'stopped';
  priceIncrease?: PriceIncrease;
  categoryId: string;
  accountId: string;
  /** Ids of the charges that make up the pattern, oldest first. */
  transactionIds: string[];
}

export interface DetectOptions {
  now?: number;
  /** Subscription ids the user marked "Not a subscription". */
  dismissed?: Iterable<string>;
  /** Patterns below this confidence are dropped (0..1). */
  minConfidence?: number;
}

interface Charge {
  id: string;
  time: number;
  day: number;
  amount: number;
  categoryId: string;
  accountId: string;
  label: string;
  ids: string[];
}

const isoDay = (time: number) => new Date(time).toISOString().slice(0, 10);
const dayIndex = (time: number) => Math.floor(time / DAY_MS);

const median = (values: readonly number[]): number => {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = sorted.length >> 1;
  return sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
};

const round2 = (value: number) => Math.round(value * 100) / 100;

/** Smallest rise that counts as a price change, per currency. */
const minAbsoluteRise = (currency: Currency) => (currency === 'RSD' ? 50 : 0.5);

// Web and payment-processor noise that varies between statements of the same service.
const NOISE_TOKENS = new Set(['www', 'http', 'https', 'com', 'net', 'org', 'rs', 'io', 'app', 'eu', 'paypal', 'payment', 'placanje', 'pretplata', 'subscription']);

/** Merchant key for subscription grouping: the shared merchant key minus web noise. */
export const subscriptionKey = (value: string | null | undefined): string =>
  normalizeMerchant(merchantTokens(value).filter(token => !NOISE_TOKENS.has(token)).join(' '));

const merchantSource = (transaction: Transaction): string =>
  transaction.receiptData?.merchant?.trim() || transaction.note?.trim() || '';

/** A charge the user already tracks: generated by a recurring rule. */
const isRecurringOccurrence = (transaction: Transaction) => transaction.id.startsWith('rec:');

const cadenceFor = (gap: number): CadenceRule | undefined => CADENCES.find(rule => gap >= rule.min && gap <= rule.max);

/**
 * The longest run of charges at the latest cadence, walking back from the newest charge.
 * One missed cycle (a double gap) is tolerated so a skipped month does not hide a subscription.
 */
const latestRun = (charges: readonly Charge[]): { rule: CadenceRule; run: Charge[]; gaps: number[] } | null => {
  if (charges.length < 2) return null;
  const lastGap = charges[charges.length - 1].day - charges[charges.length - 2].day;
  // The newest gap may itself be a skipped cycle; try the single and the halved gap.
  const candidates = [cadenceFor(lastGap), cadenceFor(lastGap / 2)].filter((rule): rule is CadenceRule => Boolean(rule));
  let best: { rule: CadenceRule; run: Charge[]; gaps: number[] } | null = null;
  for (const rule of candidates) {
    const run: Charge[] = [charges[charges.length - 1]];
    const gaps: number[] = [];
    let skips = 0;
    let extras = 0;
    for (let i = charges.length - 2; i >= 0; i -= 1) {
      const gap = run[0].day - charges[i].day;
      if (gap >= rule.min && gap <= rule.max) {
        gaps.unshift(gap);
        run.unshift(charges[i]);
      } else if (skips === 0 && gap >= rule.min * 2 && gap <= rule.max * 2) {
        skips += 1;
        gaps.unshift(gap / 2);
        run.unshift(charges[i]);
      } else if (gap < rule.min) {
        // An extra charge inside the cycle (a one-off purchase at the same shop): skip it, keep walking.
        extras += 1;
        continue;
      } else {
        break;
      }
    }
    // A shop visited between "cycles" all the time (a café, a supermarket) is a habit, not a
    // subscription, even if some visits happen to line up.
    if (extras > Math.max(1, Math.floor(run.length / 3))) continue;
    if (run.length >= rule.minCount && (!best || run.length > best.run.length)) best = { rule, run, gaps };
  }
  return best;
};

/** Latest meaningful price rise inside the run, if it happened in the last few cycles. */
const findPriceIncrease = (run: readonly Charge[], currency: Currency, periodDays: number, now: number): PriceIncrease | undefined => {
  const threshold = minAbsoluteRise(currency);
  for (let i = run.length - 1; i >= 1; i -= 1) {
    const before = run[i - 1].amount;
    const after = run[i].amount;
    if (after - before > threshold && after > before * 1.03) {
      // The new price must have held (or be the newest charge), so a one-off extra is not a "rise".
      const held = run.slice(i).every(charge => charge.amount >= after * 0.97);
      if (!held) return undefined;
      if (now - run[i].time > periodDays * 3.5 * DAY_MS) return undefined;
      // Compare against the stable price before the change, not a single possibly odd charge.
      const previous = median(run.slice(Math.max(0, i - 3), i).map(charge => charge.amount));
      if (after - previous <= threshold || after <= previous * 1.03) return undefined;
      return { from: round2(previous), to: round2(after), pct: (after - previous) / previous, date: isoDay(run[i].time) };
    }
  }
  return undefined;
};

/** Next expected charge after the last one, rolled forward past today; monthly keeps the day of month. */
const nextDateFor = (rule: CadenceRule, lastTime: number, now: number, status: 'active' | 'stopped'): string => {
  const step = (time: number): number => {
    if (rule.cadence === 'monthly' || rule.cadence === 'quarterly' || rule.cadence === 'yearly') {
      const months = rule.cadence === 'monthly' ? 1 : rule.cadence === 'quarterly' ? 3 : 12;
      const date = new Date(time);
      const day = date.getUTCDate();
      const target = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth() + months, 1));
      const lastDay = new Date(Date.UTC(target.getUTCFullYear(), target.getUTCMonth() + 1, 0)).getUTCDate();
      target.setUTCDate(Math.min(day, lastDay));
      return target.getTime();
    }
    return time + rule.days * DAY_MS;
  };
  let next = step(lastTime);
  if (status === 'active') {
    const today = dayIndex(now) * DAY_MS;
    for (let guard = 0; next < today && guard < 60; guard += 1) next = step(next);
  }
  return isoDay(next);
};

/** Rules the user already has, reduced to what matching needs. */
const recurringMatchers = (recurring: readonly RecurringTransaction[]) =>
  recurring
    .filter(rule => rule.type === 'expense')
    .map(rule => ({
      tokens: new Set([...merchantTokens(rule.name), ...merchantTokens(rule.note)]),
      currency: rule.currency,
      amount: rule.amount,
    }))
    .filter(rule => rule.tokens.size > 0);

const coveredByRecurring = (
  key: string,
  currency: Currency,
  amount: number,
  matchers: ReturnType<typeof recurringMatchers>,
): boolean => {
  const tokens = key.split(' ');
  return matchers.some(
    rule =>
      rule.currency === currency &&
      tokens.some(token => token.length >= 3 && rule.tokens.has(token)) &&
      Math.abs(rule.amount - amount) <= Math.max(rule.amount, amount) * 0.3,
  );
};

const mostCommon = (values: readonly string[]): string => {
  const counts = new Map<string, number>();
  let bestValue = values[values.length - 1] ?? '';
  let bestCount = 0;
  for (const value of values) {
    const count = (counts.get(value) ?? 0) + 1;
    counts.set(value, count);
    if (count >= bestCount) {
      bestCount = count;
      bestValue = value;
    }
  }
  return bestValue;
};

/** Groups expenses by normalized merchant and currency, merging same-day charges. */
const groupCharges = (transactions: readonly Transaction[]): Map<string, { key: string; currency: Currency; charges: Charge[] }> => {
  const groups = new Map<string, { key: string; currency: Currency; charges: Charge[] }>();
  for (const transaction of transactions) {
    if (transaction.type !== 'expense' || transaction.transferId || transaction.categoryId === 'internal-transfer') continue;
    if (isRecurringOccurrence(transaction) || !(transaction.amount > 0)) continue;
    const label = merchantSource(transaction);
    const key = subscriptionKey(label);
    if (key.length < 3) continue;
    const time = Date.parse(transaction.date);
    if (!Number.isFinite(time)) continue;
    const id = `${key}|${transaction.currency}`;
    let group = groups.get(id);
    if (!group) {
      group = { key, currency: transaction.currency, charges: [] };
      groups.set(id, group);
    }
    group.charges.push({
      id: transaction.id,
      time,
      day: dayIndex(time),
      amount: transaction.amount,
      categoryId: transaction.categoryId,
      accountId: transaction.accountId,
      label,
      ids: [transaction.id],
    });
  }
  for (const group of groups.values()) {
    group.charges.sort((a, b) => a.time - b.time);
    const merged: Charge[] = [];
    for (const charge of group.charges) {
      const previous = merged[merged.length - 1];
      if (previous && previous.day === charge.day) {
        previous.amount += charge.amount;
        previous.ids.push(...charge.ids);
        previous.time = Math.max(previous.time, charge.time);
        previous.label = charge.label;
      } else {
        merged.push({ ...charge, ids: [...charge.ids] });
      }
    }
    group.charges = merged;
  }
  return mergeSpellings(groups);
};

/**
 * "Namecheap" and "Namecheap domain renewal" are one merchant when the longer key starts with the
 * shorter one and the typical prices agree; different products of one company ("Google One" vs
 * "Google Play") stay apart because their prices differ.
 */
const mergeSpellings = (groups: Map<string, { key: string; currency: Currency; charges: Charge[] }>) => {
  const ordered = [...groups.entries()].sort((a, b) => a[1].key.length - b[1].key.length);
  for (const [id, group] of ordered) {
    const tokens = group.key.split(' ');
    for (let n = tokens.length - 1; n >= 1; n -= 1) {
      const prefix = tokens.slice(0, n).join(' ');
      if (prefix.length < 4) break;
      const target = groups.get(`${prefix}|${group.currency}`);
      if (!target || target === group) continue;
      const a = median(group.charges.map(charge => charge.amount));
      const b = median(target.charges.map(charge => charge.amount));
      if (Math.abs(a - b) > Math.max(a, b) * 0.2) continue;
      const combined = [...target.charges, ...group.charges].sort((x, y) => x.time - y.time);
      const merged: Charge[] = [];
      for (const charge of combined) {
        const previous = merged[merged.length - 1];
        if (previous && previous.day === charge.day) {
          previous.amount += charge.amount;
          previous.ids.push(...charge.ids);
        } else {
          merged.push(charge);
        }
      }
      target.charges = merged;
      groups.delete(id);
      break;
    }
  }
  return groups;
};

/**
 * Detects subscriptions from history. Recurring rules the user already has are excluded (both
 * their generated charges and manual charges that look like them), as are dismissed ids.
 * Sorted: price increases first, then active by monthly cost, then stopped.
 */
export const detectSubscriptions = (
  transactions: readonly Transaction[],
  recurring: readonly RecurringTransaction[] = [],
  options: DetectOptions = {},
): DetectedSubscription[] => {
  const now = options.now ?? Date.now();
  const dismissed = new Set(options.dismissed ?? []);
  const minConfidence = options.minConfidence ?? 0.5;
  const matchers = recurringMatchers(recurring);
  const results: DetectedSubscription[] = [];

  for (const [id, group] of groupCharges(transactions)) {
    if (dismissed.has(id)) continue;
    const found = latestRun(group.charges);
    if (!found) continue;
    const { rule, run, gaps } = found;
    const latest = run[run.length - 1];

    // Amounts must be similar: most charges within 20 % of the median (bills vary a little).
    // Weekly and biweekly charges must be near exact, or every weekly grocery run would qualify.
    const amounts = run.map(charge => charge.amount);
    const mid = median(amounts);
    const frequent = rule.cadence === 'weekly' || rule.cadence === 'biweekly';
    const tolerance = frequent ? 0.03 : 0.2;
    const stableShare = amounts.filter(amount => Math.abs(amount - mid) <= mid * tolerance).length / amounts.length;
    if (stableShare < (frequent ? 0.9 : 0.7)) continue;
    if (coveredByRecurring(group.key, group.currency, latest.amount, matchers)) continue;

    const periodDays = median(gaps) || rule.days;
    const regularity = 1 - Math.min(1, median(gaps.map(gap => Math.abs(gap - periodDays))) / Math.max(2, periodDays * 0.15));
    const countScore = Math.min(1, (run.length - 1) / Math.max(2, rule.minCount + 1));
    const confidence = round2(0.4 * countScore + 0.35 * regularity + 0.25 * stableShare);
    if (confidence < minConfidence) continue;

    const overdueDays = (now - latest.time) / DAY_MS;
    const status: 'active' | 'stopped' = overdueDays > periodDays * 2 + (rule.max - rule.days) ? 'stopped' : 'active';
    const monthlyCost = round2((latest.amount * AVG_MONTH_DAYS) / rule.days);

    results.push({
      id,
      key: group.key,
      label: latest.label,
      currency: group.currency,
      cadence: rule.cadence,
      periodDays: Math.round(periodDays),
      amount: round2(latest.amount),
      count: run.length,
      firstDate: isoDay(run[0].time),
      lastDate: isoDay(latest.time),
      nextDate: nextDateFor(rule, latest.time, now, status),
      monthlyCost,
      yearlyCost: round2(monthlyCost * 12),
      confidence,
      status,
      priceIncrease: status === 'active' ? findPriceIncrease(run, group.currency, rule.days, now) : undefined,
      categoryId: mostCommon(run.map(charge => charge.categoryId)),
      accountId: latest.accountId,
      transactionIds: run.flatMap(charge => charge.ids),
    });
  }

  return results.sort((a, b) => {
    if (a.status !== b.status) return a.status === 'active' ? -1 : 1;
    if (Boolean(a.priceIncrease) !== Boolean(b.priceIncrease)) return a.priceIncrease ? -1 : 1;
    return b.monthlyCost - a.monthlyCost;
  });
};

/** Total monthly and yearly cost of active subscriptions, in the caller's currency. */
export const subscriptionTotals = (
  items: readonly DetectedSubscription[],
  convert: (amount: number, from: Currency) => number,
): { monthly: number; yearly: number; count: number } => {
  const active = items.filter(item => item.status === 'active');
  const monthly = round2(active.reduce((sum, item) => sum + convert(item.monthlyCost, item.currency), 0));
  return { monthly, yearly: round2(monthly * 12), count: active.length };
};

/** Recurring rule draft for "Track as recurring"; undefined for cadences the rules cannot express. */
export const recurringFromSubscription = (
  item: DetectedSubscription,
  name: string,
  makeId: () => string,
): RecurringTransaction | undefined => {
  const frequency = CADENCE_FREQUENCY[item.cadence];
  if (!frequency) return undefined;
  return {
    id: makeId(),
    name: name.slice(0, 100),
    amount: item.amount,
    currency: item.currency,
    categoryId: item.categoryId,
    accountId: item.accountId,
    type: 'expense',
    note: name.slice(0, 100),
    frequency,
    // Start at the next expected charge so past charges (already in history) are not generated again.
    startDate: item.nextDate,
    nextDue: item.nextDate,
    isActive: true,
  };
};

/** Once-only key for a price-increase alert: merchant plus the date and price of the change. */
export const priceIncreaseKey = (item: DetectedSubscription): string | undefined =>
  item.priceIncrease ? `${item.id}@${item.priceIncrease.date}:${item.priceIncrease.to}` : undefined;
