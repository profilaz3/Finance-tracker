/**
 * The seed categories were created with generic icons (Food & Dining with a coffee cup, Health
 * with a pulse line). While a seed category still carries its original icon, show a clearer one.
 * A category whose icon the user picked keeps it.
 */
const SEED_ICON_UPGRADES: Record<string, [string, LucideIcon]> = {
    c1: ['coffee', Utensils],
    c4: ['wallet', Briefcase],
    c5: ['gamepad', Clapperboard],
    c6: ['activity', HeartPulse],
    c8: ['refresh-cw', HandCoins],
};

export const getIconByName = (iconName: string): LucideIcon => {
    return ICON_NAME_MAP[iconName] || Wallet;
};

/** The icon for a category: its explicit icon name, else a guess from its name. */
export const iconForCategory = (category?: { id?: string; name?: string; icon?: string }): LucideIcon => {
    const upgrade = category?.id ? SEED_ICON_UPGRADES[category.id] : undefined;
    if (upgrade && category?.icon === upgrade[0]) return upgrade[1];
    return category?.icon && ICON_NAME_MAP[category.icon] ? ICON_NAME_MAP[category.icon] : getCategoryIcon(category?.name ?? '');
};
